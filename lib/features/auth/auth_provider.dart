import 'dart:convert';

import 'package:flutter/material.dart';

import '../../core/api/api_client.dart';
import '../../core/api/api_endpoints.dart';
import '../../core/helpers/storage_helper.dart';

class AuthProvider extends ChangeNotifier {
  /*
  |--------------------------------------------------------------------------
  | USER DATA
  |--------------------------------------------------------------------------
  */

  String? token;

  Map<String, dynamic>? user;

  /*
  |--------------------------------------------------------------------------
  | LOGIN STATUS
  |--------------------------------------------------------------------------
  */

  bool get isLoggedIn => token != null;

  /*
  |--------------------------------------------------------------------------
  | REGISTER USER
  |--------------------------------------------------------------------------
  */

  Future<bool> registerUser(
    String name,

    String email,

    String phone,

    String password,
  ) async {
    try {
      /*
      |--------------------------------------------------------------------------
      | API CALL
      |--------------------------------------------------------------------------
      */

      final data = await ApiClient.post(ApiEndpoints.register, {
        "name": name,

        "email": email,

        "phone": phone,

        "password": password,
      });

      debugPrint("REGISTER RESPONSE => $data");

      /*
      |--------------------------------------------------------------------------
      | SUCCESS CHECK
      |--------------------------------------------------------------------------
      */

      if (data["success"] == true || data["code"] == 200) {
        /*
        |--------------------------------------------------------------------------
        | AUTO LOGIN
        |--------------------------------------------------------------------------
        */

        return await login(email, password);
      }

      return false;
    } catch (e) {
      debugPrint("REGISTER ERROR => $e");

      return false;
    }
  }

  /*
  |--------------------------------------------------------------------------
  | LOGIN USER
  |--------------------------------------------------------------------------
  */

  Future<bool> login(String email, String password) async {
    try {
      /*
      |--------------------------------------------------------------------------
      | API CALL
      |--------------------------------------------------------------------------
      */

      final data = await ApiClient.post(ApiEndpoints.login, {
        "email": email,

        "password": password,
      });

      debugPrint("LOGIN RESPONSE => $data");

      /*
      |--------------------------------------------------------------------------
      | SUCCESS CHECK
      |--------------------------------------------------------------------------
      */

      if (data["success"] == true || data["code"] == 200) {
        /*
        |--------------------------------------------------------------------------
        | TOKEN
        |--------------------------------------------------------------------------
        */

        token = data["data"]["token"];

        /*
        |--------------------------------------------------------------------------
        | USER
        |--------------------------------------------------------------------------
        */

        user = data["data"]["user"];

        /*
        |--------------------------------------------------------------------------
        | SAVE TOKEN
        |--------------------------------------------------------------------------
        */

        await StorageHelper.saveToken(token!);

        /*
        |--------------------------------------------------------------------------
        | SAVE USER
        |--------------------------------------------------------------------------
        */

        await StorageHelper.saveUser(jsonEncode(user));

        debugPrint("TOKEN SAVED => $token");

        debugPrint("USER SAVED => $user");

        notifyListeners();

        return true;
      }

      return false;
    } catch (e) {
      debugPrint("LOGIN ERROR => $e");

      return false;
    }
  }

  /*
  |--------------------------------------------------------------------------
  | AUTO LOAD USER
  |--------------------------------------------------------------------------
  */

  Future<void> loadUser() async {
    /*
    |--------------------------------------------------------------------------
    | GET TOKEN
    |--------------------------------------------------------------------------
    */

    token = await StorageHelper.getToken();

    /*
    |--------------------------------------------------------------------------
    | GET USER
    |--------------------------------------------------------------------------
    */

    String? userJson = await StorageHelper.getUser();

    /*
    |--------------------------------------------------------------------------
    | DECODE USER
    |--------------------------------------------------------------------------
    */

    if (userJson != null) {
      user = jsonDecode(userJson);
    }

    notifyListeners();
  }

  /*
  |--------------------------------------------------------------------------
  | LOGOUT
  |--------------------------------------------------------------------------
  */

  Future<void> logout() async {
    token = null;

    user = null;

    await StorageHelper.logout();

    notifyListeners();
  }
}
